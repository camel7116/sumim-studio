/* ── 지그재그 path 생성 (서버에서 한 번, 결정적) ───────────────────────────── */

const VB_W = 1000;
const VB_H = 100;
const ZIG_STEPS = 34;
/** 고리(급격히 되꺾이는 훅)를 넣을 꼭짓점 인덱스 — 고정 */
const ZIG_LOOP_AT = [7, 18, 28];

/** 하드코딩 의사난수 (mulberry32). 같은 시드면 서버·클라이언트가 같은 값을 낸다 */
function rng(seed: number) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** 불규칙 지그재그 전선 — 꼭짓점 수는 키프레임마다 **항상 같다**(SMIL 보간 조건) */
function zigzagFront(anchor: "l" | "r", progress: number, ampX: number, seed: number) {
  const front = anchor === "l" ? VB_W * (1 - progress) : VB_W * progress;
  const rand = rng(seed);
  const pts: string[] = [];
  const push = (x: number, y: number) => pts.push(`${x.toFixed(1)},${y.toFixed(1)}`);
  for (let i = 0; i <= ZIG_STEPS; i += 1) {
    const y = -2 + (i / ZIG_STEPS) * (VB_H + 4);
    let off = rand() * 2 - 1;
    const kind = rand();
    if (kind > 0.86) off *= 3.1; // 긴 톱니
    else if (kind > 0.7) off *= 0.22; // 아주 짧은 톱니
    push(front + off * ampX, y);
    if (ZIG_LOOP_AT.includes(i)) {
      // 고리 — 크게 튀어나갔다가 기준선을 넘어 되꺾이고 다시 나간다(evenodd 라 구멍으로 보인다)
      const dy = (VB_H + 4) / ZIG_STEPS;
      push(front + (2.4 + rand()) * ampX, y + dy * 0.35);
      push(front - (1.8 + rand()) * ampX, y + dy * 0.2);
      push(front + (1.5 + rand()) * ampX, y + dy * 0.7);
    }
  }
  const outer = anchor === "l" ? -40 : VB_W + 40;
  return `M${outer},-2 L${pts.join(" L")} L${outer},${VB_H + 2} Z`;
}

/**
 * `split` 용 지그재그 — 기준선은 **고정**이고(전진은 CSS transform 이 맡는다)
 * 꼭짓점마다 자기 위상으로 **사인 꿈틀**만 더한다. `phase` 를 0→1 로 돌리면 한 바퀴 돌아
 * 첫 키프레임과 정확히 다시 만나므로 SMIL 이 이음매 없이 반복된다.
 * 톱니 길이 분포(긴 톱니 ×3.1 · 짧은 톱니 ×0.22)와 고리는 `zigzagFront` 와 같은 규칙이다.
 */
function splitZigzag(anchor: "l" | "r", frontUnits: number, ampX: number, wobX: number, seed: number, phase: number) {
  const rand = rng(seed);
  const pts: string[] = [];
  const push = (x: number, y: number) => pts.push(`${x.toFixed(1)},${y.toFixed(1)}`);
  const wob = (i: number, ph: number) => wobX * Math.sin(2 * Math.PI * (phase + ph + i * 0.137));
  const loopAt = [2, 6, 9];
  for (let i = 0; i <= SPLIT_STEPS; i += 1) {
    const y = -2 + (i / SPLIT_STEPS) * (VB_H + 4);
    let off = rand() * 2 - 1;
    const kind = rand();
    const ph = rand();
    if (kind > 0.8) off *= 2.2; // 긴 톱니
    else if (kind > 0.62) off *= 0.25; // 아주 짧은 톱니
    push(frontUnits + off * ampX + wob(i, ph), y);
    if (loopAt.includes(i)) {
      // 고리 — 크게 튀어나갔다가 기준선을 넘어 되꺾이고 다시 나간다
      const dy = (VB_H + 4) / SPLIT_STEPS;
      push(frontUnits + (1.7 + rand() * 0.6) * ampX + wob(i, ph), y + dy * 0.3);
      push(frontUnits - (1.3 + rand() * 0.6) * ampX + wob(i + 1, ph), y + dy * 0.5);
      push(frontUnits + (1.1 + rand() * 0.5) * ampX + wob(i + 2, ph), y + dy * 0.75);
    }
  }
  const outer = anchor === "l" ? -60 : VB_W + 60;
  return `M${outer},-2 L${pts.join(" L")} L${outer},${VB_H + 2} Z`;
}

/**
 * `split` 덮개 2장의 기하 — 전부 **래퍼 좌표계(em)** 다.
 * (`<p>` 는 `margin-left: -광학보정` 이라 잉크 왼끝이 래퍼 왼쪽보다 그만큼 왼쪽에 있다.)
 */
function buildSplitVeils() {
  const inkL = -WM_OPTICAL_EM;
  const inkR = WM_TOTAL_INK - WM_OPTICAL_EM;
  const colL = BOX_X_SLOT - WM_OPTICAL_EM;
  const colR = BOX_X_SLOT + BOX_SLOT - WM_OPTICAL_EM;
  const T = SPLIT_TOOTH_EM;
  const mk = (side: "l" | "r", bandW: number, elemLeft: number, seed: number) => {
    const elemW = bandW + T;
    const frontUnits = side === "l" ? (bandW / elemW) * VB_W : (T / elemW) * VB_W;
    const ampX = (SPLIT_AMP_EM / elemW) * VB_W;
    const wobX = (SPLIT_WOBBLE_EM / elemW) * VB_W;
    const values: string[] = [];
    for (let k = 0; k < SPLIT_WOBBLE_KEYS; k += 1)
      values.push(splitZigzag(side, frontUnits, ampX, wobX, seed, k / (SPLIT_WOBBLE_KEYS - 1)));
    return { side, left: elemLeft, width: elemW, values };
  };
  // 🚨 기준선을 기둥 **안쪽으로 H** 밀어 넣어(= 밴드 폭을 H 만큼 늘려) 완전 은폐를 만든다
  const H = SPLIT_HIDE_EM;
  return [
    mk("l", colL + H - (inkL - SPLIT_OVERHANG_EM), inkL - SPLIT_OVERHANG_EM, 5171),
    mk("r", inkR + SPLIT_OVERHANG_EM - (colR - H), colR - H - T, 8837),
  ];
}

/** 씨앗 구멍 — 같은 결의 불규칙 다각형 (반지름이 제각각) */
function seedHole(cx: number, cy: number, rx: number, ry: number, seed: number) {
  const rand = rng(seed);
  const n = 22;
  const pts: string[] = [];
  for (let i = 0; i < n; i += 1) {
    const a = (i / n) * Math.PI * 2;
    const j = 0.62 + rand() * 0.76;
    pts.push(`${(cx + Math.cos(a) * rx * j).toFixed(1)},${(cy + Math.sin(a) * ry * j).toFixed(1)}`);
  }
  return ` M${pts[0]} L${pts.slice(1).join(" L")} Z`;
}

/** SMIL 키프레임 수 — 전선 위치·지터·씨앗 반지름을 함께 굽는다 */
const KEYS = 9;

/**
 * 씨앗 x (줄 잉크 왼끝 기준 em) — 칸 안 글자의 **advance 18% 지점**을 스케일·자간 반영해 환산.
 * 🚨 글자 **정중앙이 아니라 왼쪽 획 위**다 — U·O 처럼 속이 빈 글자는 정중앙이 카운터(배경색)라
 *    구멍을 뚫어도 아무것도 안 보인다(2026-08-22 실측 전례).
 */
function seedXEm(cell: CellSpec, cellX: number, glyphIndex: number) {
  let local = 0;
  for (let i = 0; i <= glyphIndex; i += 1) local += cell.kern?.[i] ?? 0; // 글자별 커닝 누적
  for (let i = 0; i < glyphIndex; i += 1) local += cell.advances[i] + cell.ls;
  local += cell.advances[glyphIndex] * 0.18;
  return cellX + cell.scaleX * (local - cell.lsb);
}

type VeilPlan = {
  left: number;
  width: number;
  anchor: "l" | "r";
  values: string[];
  keyTimes: string[];
  begin: number;
};

/**
 * 덮개 2장(기둥 왼쪽 / 오른쪽)을 서버에서 계산한다. **두 줄이 같은 좌표**다.
 * 전선 진행 곡선은 **코사인 ease-in-out** `p = (1 − cos(πt))/2` — 시작이 가파르면
 * (`t^0.75`) 씨앗 섬이 보이기도 전에 흡수돼 버린다(2026-08-22 실측 전례).
 */
function buildVeils(lineIndex: number, begin: number): VeilPlan[] {
  const c = WM_CELLS[lineIndex];
  // 씨앗 — 좌측 칸의 가운데 글자 + 우측 칸의 한 글자
  const seeds: number[] = [];
  if (SEED_COUNT > 0) {
    const mid = Math.round((c.left.text.length - 1) / 2);
    seeds.push(seedXEm(c.left, BOX_X_LEFT, mid));
  }
  if (SEED_COUNT > 1) seeds.push(seedXEm(c.right, BOX_X_RIGHT, 0));

  const bands: { left: number; width: number; anchor: "l" | "r"; seed: number }[] = [
    {
      left: -VEIL_OVERHANG_EM,
      width: BOX_X_SLOT + VEIL_OVERHANG_EM,
      anchor: "l",
      seed: 1013 + lineIndex * 97,
    },
    {
      left: BOX_X_SLOT + BOX_SLOT,
      width: WM_TOTAL_INK + VEIL_OVERHANG_EM - (BOX_X_SLOT + BOX_SLOT),
      anchor: "r",
      seed: 2711 + lineIndex * 131,
    },
  ];

  return bands.map<VeilPlan>((b) => {
    const ampX = (VEIL_AMP_EM / b.width) * VB_W;
    const mine = seeds.filter((sx) => sx > b.left && sx < b.left + b.width);
    const values: string[] = [];
    const keyTimes: string[] = [];
    for (let k = 0; k < KEYS; k += 1) {
      const t = k / (KEYS - 1);
      const p = (1 - Math.cos(Math.PI * t)) / 2;
      let d = zigzagFront(b.anchor, p, ampX, b.seed + k * 7919);
      const elapsed = t * SPREAD_DURATION;
      const grow =
        elapsed <= SPREAD_SEED_BEGIN
          ? 0
          : Math.min(1, Math.pow((elapsed - SPREAD_SEED_BEGIN) / SPREAD_SEED_GROWTH, 0.8));
      const rEm = SPREAD_SEED_RADIUS_EM * grow;
      const front = b.anchor === "l" ? VB_W * (1 - p) : VB_W * p;
      mine.forEach((sx, si) => {
        const cx = ((sx - b.left) / b.width) * VB_W;
        const rxU = (rEm / b.width) * VB_W;
        /*
          🚨 **전선이 지나간 씨앗은 반드시 0 으로 줄여야 한다.** `fill-rule="evenodd"` 라
          덮개 바깥으로 남은 구멍 서브패스는 구멍이 아니라 **채워진 얼룩**이 되어 글자 위에
          검은 조각으로 남는다(2026-08-22 첫 캡처에서 실제로 그렇게 나왔다).
        */
        const inside = b.anchor === "l" ? front - cx : cx - front;
        const shrink = Math.max(0, Math.min(1, (inside - 2) / Math.max(rxU, 1)));
        if (rxU * shrink > 1) {
          d += seedHole(
            cx,
            VB_H * 0.46,
            rxU * shrink,
            (rEm / 0.82) * VB_H * shrink,
            b.seed + si * 313 + k * 41,
          );
        }
      });
      values.push(d);
      keyTimes.push(t.toFixed(4));
    }
    return { ...b, values, keyTimes, begin };
  });
}

/** 칸 하나 — `.wordmark-glyph`(칸, 고정 폭) > `.wordmark-shift`(진입 이동) > `.wordmark-fit`(글자) */
function Cell({
  spec,
  widthEm,
  offsetEm,
  marginLeftEm,
  isAccent,
  slide,
  delay,
  waveOriginEm = 0,
  overlay,
}: {
  spec: CellSpec;
  widthEm: number;
  /** 앞 칸과의 간격 (margin-left, em) */
  offsetEm: number;
  /** 칸 안에서 글자를 미는 양 (em, 스케일 전 좌표) */
  marginLeftEm: number;
  /** 🌊 `fill` 파도 — 줄 왼끝 기준 이 칸의 x 위치(em). 칸 사이 물결 위상을 이어 붙인다 */
  waveOriginEm?: number;
  isAccent?: boolean;
  /** Phase 1 — 이 칸을 **자기 오른쪽 벽 뒤에서 스윽** 밀어낸다 (`split` 의 액센트 칸만) */
  slide?: boolean;
  /**
   * 🆕 `intro` 의 **물 복제본**인가 (2026-08-24). 복제본은 글자 모양만 필요하므로
   * 파도(`wavefill`)·진입 이동·덮개 위 승격을 전부 끈다 — 물결은 줄 `<p>` 의 마스크가 낸다.
   */
  overlay?: boolean;
  delay: number;
}) {
  const kern = spec.kern;
  const waveOn = WAVE_FILL && !overlay && (WAVE_ON_ACCENT || !isAccent);
  /*
    🚨 **`slide` 칸은 파도를 한 층 안쪽(`.wordmark-shift`)에 건다** (2026-08-24 실측).
    `.wordmark-shift` 에 진입 `translateX` 애니메이션이 걸려 있으면 크롬이 그 층을 따로 합성해
    **조상 칸의 `background-clip: text` 가 그 글자를 못 잡습니다** — 배경이 클립될 글자가 없어져
    액센트 `I` 가 **통째로 사라집니다**(캡처로 확인). transform 이 걸린 요소 자신에게 걸면 정상입니다.
    ⚠️ 두 상자의 왼쪽 변이 정확히 같아야 물결 위상이 이어진다 — 실측 결과 `.wordmark-shift` 의
       왼쪽 변 = 칸의 왼쪽 변이라 `--wm-wave-org` 를 그대로 넘겨도 어긋나지 않습니다.
  */
  const waveOnShift = waveOn && slide === true;
  const waveVars = { "--wm-wave-org": `${(-waveOriginEm).toFixed(5)}em` } as CSSProperties;
  return (
    <span
      className={cn(
        "wordmark-glyph",
        slide && "wordmark-slide",
        /*
          🌊 파도. 2026-08-24 저녁부터 **액센트 칸에도 건다**(`WAVE_ON_ACCENT`) — `I` 가 흰색이
             되면서 기둥만 무늬 없이 남으면 물결이 거기서 끊기기 때문이다.
          🚨 `wordmark-wavefill` 은 글자를 `-webkit-text-fill-color: transparent` 로 비우고
             배경으로 칠한다 — 그래서 액센트에 `.text-cta`(글자색)를 같이 주면 **아무 효과가 없다**.
             보라 `I` 로 되돌릴 때는 `ACCENT_TINT` 와 함께 `WAVE_ON_ACCENT` 를 꺼야 한다.
        */
        waveOn && !waveOnShift && "wordmark-wavefill",
        WAVE_DISPLACE && !overlay && !isAccent && "wordmark-wave",
        /*
          액센트만 덮개 위 층으로 올려 처음부터 보이게 한다.
          - `split` : **항상**. 덮개가 기둥을 안 덮어도 페더(blur 3σ ≈ 0.3em)가 양옆에서
            기둥(0.307em) 안쪽까지 번져 "!"·"i" 가 흐려진다(실측). 위 층으로 올리면 확실하다.
          - `wipe` : `wipeKeepAccent` 가 켜져 있을 때만.
        */
        isAccent &&
          !overlay &&
          (SPLIT || (WIPE && hero.wordmark.wipeKeepAccent)) &&
          "wordmark-cell--above",
      )}
      style={
        {
          width: `${widthEm.toFixed(5)}em`,
          marginLeft: `${offsetEm.toFixed(5)}em`,
          ...(slide ? { "--slide-dur": `${SLIDE_DURATION}s` } : null),
          // 🌊 물결 위상 이어 붙이기 — 칸이 줄 왼끝에서 떨어진 만큼 배경을 뒤로 민다
          ...(waveOn && !waveOnShift ? waveVars : null),
        } as CSSProperties
      }
    >
      <span
        className={cn("wordmark-shift", waveOnShift && "wordmark-wavefill")}
        style={{
          ...(STILL ? null : { animationDelay: `${delay.toFixed(2)}s` }),
          ...(waveOnShift ? waveVars : null),
        }}
      >
        <span
          /* 🎨 `ACCENT_TINT` 가 `true` 일 때만 액센트가 CTA 보라 — 지금은 `I` 도 흰 잉크다 */
          className={cn("wordmark-fit", isAccent && ACCENT_TINT && "text-cta")}
          style={{
            marginLeft: `${marginLeftEm.toFixed(5)}em`,
            fontWeight: spec.weight,
            letterSpacing: `${spec.ls}em`,
            ...(spec.scaleX === 1 ? null : { transform: `scaleX(${spec.scaleX})` }),
          }}
        >
          {spec.flipY ? (
            /*
              🔄 **세로 뒤집기 전용 래퍼** (2026-08-23). 🚨 반드시 층을 따로 둔다 —
              `.wordmark-fit` 에는 3칸 규칙의 `transform-origin: left center` 와 칸별 `scaleX` 가,
              그 위 `.wordmark-shift` 에는 진입 `translateX` 애니메이션이 걸린다. 같은 요소에
              얹으면 transform 이 통째로 덮여 서로 지운다(2026-08-23 3칸 절의 같은 교훈).
              래퍼는 레이아웃을 바꾸지 않는다(inline-block 이고 베이스라인이 그대로라 폭·위치 불변).
            */
            <span
              className="wordmark-flip"
              style={
                { "--flip-origin-y": `${ACCENT_FLIP_ORIGIN_Y_EM.toFixed(4)}em` } as CSSProperties
              }
            >
              {spec.text}
            </span>
          ) : kern ? (
            // 글자별 커닝이 있으면 하나씩 쪼개 margin-left 로 민다 (자간은 그대로 먹는다)
            [...spec.text].map((ch, i) => (
              <span key={`${ch}-${i}`} style={kern[i] ? { marginLeft: `${kern[i]}em` } : undefined}>
                {ch}
              </span>
            ))
          ) : (
            spec.text
          )}
        </span>
      </span>
    </span>
  );
}

/** 3칸 박스 한 줄. `overlay` 면 `intro` 의 **물 복제본**(글자 모양만, 물결은 마스크가 낸다) */
